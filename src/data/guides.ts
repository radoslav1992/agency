/**
 * Наръчниците — това, което студиото продава като знание, а не като работа.
 *
 * Различни са от всичко останало на сайта по един начин, който има значение
 * за текста: купувачът НЕ е клиент. Той няма да ти възложи проект; той иска
 * да го направи сам. Затова тук не се продава „ще ти го направя“, а „ще
 * знаеш как“ — и това е причината страницата да казва честно за кого НЕ е.
 *
 * Наръчник, купен от човек, който после разбира, че не е за него, струва
 * повече от непродаден: връща се, пише отзив и разказва.
 */

export type Guide = {
  slug: string;
  /** Заглавието от корицата. */
  title: string;
  /** Подзаглавието — какво точно се научава. */
  subtitle: string;
  /** Едно изречение за списъци и за структурирани данни. */
  short: string;
  /** Изданието, както е изписано на корицата. */
  edition: string;
  /** Към коя дата е актуален. Наръчник за AI без дата е подозрителен. */
  current: string;
  /**
   * Името на файла с корицата в `src/assets/guides/`, без разширение.
   * Липсва ли файлът, страницата показва рамка вместо да се счупи.
   */
  cover: string;
  /** Четирите стълба от корицата — те са и структурата на наръчника. */
  pillars: { n: string; title: string; body: string }[];
  /** Конкретни неща, които читателят може СЛЕД него. Глаголи, не теми. */
  outcomes: string[];
  /** За кого е. */
  forWhom: string[];
  /** За кого НЕ е — по-важното от горното. */
  notFor: string[];
  /**
   * `soon` показва „скоро“ и форма за известяване вместо цена и бутон.
   * Цената нарочно я няма, докато не е за продан: обявена цена без начин
   * да платиш е обещание, което страницата не може да изпълни.
   */
  status: 'soon' | 'available';
};

