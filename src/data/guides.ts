/**
 * Наръчниците — това, което студиото продава като знание, а не като работа.
 *
 * Различни са от всичко останало на сайта по един начин, който има значение
 * за текста: купувачът НЕ е клиент. Той няма да ти възложи проект; той иска
 * да го направи сам. Затова тук не се продава „ще ти го направя“, а „ще
 * знаеш как“ — и това е причината страницата да казва честно за кого НЕ е.
 *
 * Наръчник, купен от човек, който после разбира, че не е за него, струва
 * повече от непродаден: връща се, пише отзив и разказва.
 */

export type Guide = {
  slug: string;
  /** Заглавието от корицата. */
  title: string;
  /** Подзаглавието — какво точно се научава. */
  subtitle: string;
  /** Едно изречение за списъци и за структурирани данни. */
  short: string;
  /** Абзацът под заглавието на собствената му страница. */
  lead: string;
  /** Изданието, както е изписано на корицата. */
  edition: string;
  /**
   * Марката, под която излиза, ако е различна от студиото.
   *
   * Не е формалност. Купувачът плаща на kova.bg, отваря файла и вижда друго
   * име в авторските права — ако страницата не го е казала предварително,
   * това е моментът, в който човек се пита дали не е купил краден файл.
   * Затова марката стои до автора, преди покупката, а не след нея.
   */
  imprint?: string;
  /** Към коя дата е актуален. Наръчник за AI без дата е подозрителен. */
  current: string;
  /**
   * Името на файла с корицата в `src/assets/guides/`, без разширение.
   * Липсва ли файлът, страницата показва рамка вместо да се счупи.
   */
  cover: string;
  /**
   * Ключът на файла в частната кофа R2 (`GUIDE_FILES`) и името, под което
   * той пристига у купувача.
   *
   * Самият файл НЕ е в хранилището и не бива да бъде: то е публично, а
   * каквото влезе в `public/`, се тегли от всеки, който познае адреса.
   * Качва се в кофата от таблото на Cloudflare или с
   * `wrangler r2 object put kova-guides/<key> --file …`.
   */
  file: { key: string; filename: string; bytes: number };
  /** Броят страници — купувачът иска да знае какво получава. */
  pages: number;
  /** Четирите стълба от корицата — те са и структурата на наръчника. */
  pillars: { n: string; title: string; body: string }[];
  /** Конкретни неща, които читателят може СЛЕД него. Глаголи, не теми. */
  outcomes: string[];
  /** За кого е. */
  forWhom: string[];
  /** За кого НЕ е — по-важното от горното. */
  notFor: string[];
  /**
   * Абзаци след общото представяне на автора — това, което важи за ТОЗИ
   * наръчник. Общата част е една за всички и стои в страницата.
   */
  authorNotes: string[];
  /**
   * `soon` показва „скоро“ и форма за известяване вместо цена и бутон.
   * Цената нарочно я няма, докато не е за продан: обявена цена без начин
   * да платиш е обещание, което страницата не може да изпълни.
   */
  status: 'soon' | 'available';
  /** Цената, когато наръчникът е за продан. Числото и валутата поотделно —
   *  изписването е едно и също навсякъде и влиза в структурираните данни. */
  price?: { amount: number; currency: 'EUR' };
  /**
   * Адресът, на който се плаща.
   *
   * Замислено е за Stripe Payment Link: един адрес, никакъв ключ в кода,
   * никакъв webhook и никакъв сървърен код за поддръжка. Stripe събира
   * парите, издава разписката и праща файла. Пускането на наръчник в
   * продажба е три реда тук — `status`, `price`, `buyUrl` — и нищо друго.
   *
   * Стигне ли се до неща, които Payment Link не може (лицензи по имейл,
   * фактури с ДДС номер, отстъпки), тогава тук идва собствен маршрут
   * `/api/guide-checkout` и ключът влиза с `wrangler secret put` — не в кода.
   */
  buyUrl?: string;
};

/**
 * Продава ли се вече. И трите условия са задължителни нарочно: „в продажба“
 * без адрес за плащане е бутон, който не води доникъде, а обявена цена без
 * бутон е обещание, което страницата не може да изпълни. Липсва ли нещо,
 * страницата се връща към „скоро“ вместо да покаже нещо счупено.
 */
export const isSellable = (guide: Guide): boolean =>
  guide.status === 'available' && Boolean(guide.buyUrl) && Boolean(guide.price);

/** Цената, изписана по български: „39 €“. */
export function priceLabel(guide: Guide): string | null {
  if (!guide.price) return null;
  const { amount, currency } = guide.price;
  return new Intl.NumberFormat('bg-BG', {
    style: 'currency',
    currency,
    minimumFractionDigits: Number.isInteger(amount) ? 0 : 2,
  }).format(amount);
}

