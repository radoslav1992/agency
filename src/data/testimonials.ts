/** Инициали от име, когато не са зададени изрично. */
export function initialsOf(t: Testimonial): string {
  if (t.initials) return t.initials;
  return t.author
    .split(/\s+/)
    .slice(0, 2)
    .map((part) => part.charAt(0).toUpperCase())
    .join('');
}
