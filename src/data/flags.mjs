/**
 * Превключватели за цели части от сайта.
 *
 * Ключът е ТУК, в хранилището, а не в таблото. Cloudflare няма поле за
 * променливи при строеж в тази сметка, а превключвателят е задължително
 * при строеж, не при заявка: сайтът е предрендериран, връзката в менюто е
 * записана в четиридесет готови HTML файла, а страниците се сервират като
 * статични ресурси, без Worker-ът изобщо да се събужда. Стойност, четена
 * при заявка, няма как да ги промени.
 *
 * Затова смяната е ред код и сливане на PR — а сливането само по себе си
 * пуска нов деплой в Cloudflare. Един ход, без табло.
 *
 * `GUIDES_ENABLED` в средата на строежа продължава да има предимство, ако
 * някога се появи къде да се сложи.
 */

/* ╔══════════════════════════════════════════════════════════════════════╗
   ║  КЛЮЧЪТ. Смени на `true` и слей — наръчниците се връщат целите.      ║
   ╚══════════════════════════════════════════════════════════════════════╝ */
const GUIDES = false;

/** `false`, `0`, `off`, `no` изключват. Всичко останало — включено. */
function enabled(value, fallback = true) {
  if (value === undefined || value === null || value === '') return fallback;
  return !/^(false|0|off|no)$/i.test(String(value).trim());
}

/*
 * Стойността влиза в пакета на Worker-а като ЛИТЕРАЛ, не се чете при заявка.
 *
 * `__GUIDES_ENABLED__` се заменя от Vite при строежа (виж `vite.define` в
 * `astro.config.mjs`). Първата версия четеше `process.env` и това мълчаливо
 * не работеше за маршрутите на Worker-а: там `process.env` се отваря при
 * ЗАЯВКА, вътре в workerd, където променливата от строежа я няма — тоест
 * страниците изчезваха, а `/api/guide-file` продължаваше да подава файла.
 *
 * В Node (когато `astro.config.mjs` внася този файл) заместване няма, затова
 * `typeof` пази обръщението и стойността идва от средата на строежа.
 */
const inlined = typeof __GUIDES_ENABLED__ !== 'undefined' ? __GUIDES_ENABLED__ : undefined;
const env = typeof process !== 'undefined' && process.env ? process.env : {};

export const FLAGS = {
  /**
   * Наръчниците: рафтът, страниците им, продажбата, свалянето и записването
   * за известие. Изключено — все едно ги няма.
   */
  guides: enabled(inlined ?? env.GUIDES_ENABLED, GUIDES),
};
